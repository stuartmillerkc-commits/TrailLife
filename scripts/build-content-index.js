#!/usr/bin/env node
// Writes content/index.json: the list of every content file.
//
// Why: a web browser can't list a folder, so the site reads this list to know
// which modules, facts and battles exist. Run `npm run index` after adding,
// renaming or deleting a content file. (`npm start` and `npm run build` do it
// for you, and `npm run check` fails if the list is out of date.)

import { writeFileSync } from "node:fs";
import path from "node:path";
import { CONTENT_INDEX_FILE, DEFAULT_CONTENT_DIRECTORY, listContentFiles } from "./lib/content-files.js";

const files = listContentFiles(DEFAULT_CONTENT_DIRECTORY);
const index = {
  note: "Generated by scripts/build-content-index.js. Don't edit by hand; run `npm run index`.",
  files
};
writeFileSync(path.join(DEFAULT_CONTENT_DIRECTORY, CONTENT_INDEX_FILE), JSON.stringify(index, null, 2) + "\n", "utf8");
console.log(`Wrote content/${CONTENT_INDEX_FILE} listing ${files.length} files.`);
